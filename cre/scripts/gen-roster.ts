#!/usr/bin/env bun
/**
 * Writes cre/market-meta/roster.ts from shared/roster.json.
 *
 * The workflow runs as WASM inside the DON and cannot read files, so the
 * roster has to be compiled in. Generating it (rather than hand-copying)
 * keeps the coin ids the workflow reports identical to the ones the game
 * clients and contracts use. `market-meta/roster.test.ts` fails if the two
 * drift, so re-run this whenever shared/roster.json changes:
 *
 *   cd cre/market-meta && bun run gen:roster
 */
// Bun APIs only (no node:* imports): the CRE SDK's type restrictions apply to
// every file typechecked alongside the workflow, and they ban Node built-ins.

const KINDS = ['crypto', 'defi', 'rwa'] as const
type Kind = (typeof KINDS)[number]

type SharedCoin = {
	coinId: number
	ticker: string
	kind: Kind
	/** Chainlink Data Feed pair, e.g. "BTC / USD". */
	pair: string
	/** keccak256(pair) on the contract side; opaque here. */
	feedId: string
	/** null only for fiat (rwa) fighters, which are priced from FX rates. */
	coingeckoId: string | null
}

/** A fiat fighter's pair: three-letter ISO 4217 code quoted in USD. */
const FIAT_PAIR = /^[A-Z]{3} \/ USD$/

const creRoot = `${import.meta.dir}/..`
const source = `${creRoot}/../shared/roster.json`
const target = `${creRoot}/market-meta/roster.ts`

const shared = (await Bun.file(source).json()) as { chainId: number; coins: SharedCoin[] }

const seen = new Set<number>()
const rows = shared.coins
	.map((c) => {
		if (!Number.isInteger(c.coinId) || c.coinId < 0 || c.coinId > 0xffff) {
			throw new Error(`coinId ${c.coinId} (${c.ticker}) does not fit uint16`)
		}
		if (seen.has(c.coinId)) throw new Error(`duplicate coinId ${c.coinId}`)
		seen.add(c.coinId)
		if (!(KINDS as readonly string[]).includes(c.kind)) {
			throw new Error(`${c.ticker} has unknown kind ${JSON.stringify(c.kind)} (expected ${KINDS.join('/')})`)
		}
		if (typeof c.pair !== 'string' || !c.pair.includes(' / ')) {
			throw new Error(`${c.ticker} has a malformed pair ${JSON.stringify(c.pair)}`)
		}
		if (typeof c.feedId !== 'string' || !/^0x[0-9a-f]{64}$/i.test(c.feedId)) {
			throw new Error(`${c.ticker} feedId is not a bytes32 hex string`)
		}
		const fiat = c.coingeckoId === null
		if (fiat) {
			// Only fiat fighters may go without a CoinGecko id: the workflow
			// prices them from FX rates keyed by the pair's currency code.
			if (c.kind !== 'rwa') throw new Error(`${c.ticker} is ${c.kind} but has no coingeckoId`)
			if (!FIAT_PAIR.test(c.pair)) {
				throw new Error(`${c.ticker} has no coingeckoId and its pair ${JSON.stringify(c.pair)} is not "XXX / USD" fiat`)
			}
		} else if (typeof c.coingeckoId !== 'string' || c.coingeckoId.length === 0) {
			throw new Error(`${c.ticker} is ${c.kind} but has no coingeckoId`)
		}
		return {
			coinId: c.coinId,
			ticker: c.ticker,
			kind: c.kind,
			pair: c.pair,
			coingeckoId: c.coingeckoId,
			feedId: c.feedId.toLowerCase(),
		}
	})
	.sort((a, b) => a.coinId - b.coinId)

const body = rows
	.map(
		(r) =>
			`\t{ coinId: ${r.coinId}, ticker: ${JSON.stringify(r.ticker)}, kind: ${JSON.stringify(r.kind)}, pair: ${JSON.stringify(r.pair)}, coingeckoId: ${JSON.stringify(r.coingeckoId)}, feedId: ${JSON.stringify(r.feedId)} },`,
	)
	.join('\n')

const out = `// GENERATED by cre/scripts/gen-roster.ts from shared/roster.json — do not edit.
// Re-run \`bun run gen:roster\` (in cre/market-meta) after changing the roster.

export type CoinKind = ${KINDS.map((k) => `'${k}'`).join(' | ')}

export type RosterCoin = {
	/** uint16 id shared by the contracts, the game clients and this workflow. */
	readonly coinId: number
	readonly ticker: string
	readonly kind: CoinKind
	/** Chainlink Data Feed pair on Arc mainnet, e.g. "BTC / USD". */
	readonly pair: string
	/** CoinGecko id; null for fiat fighters ("XXX / USD", priced from FX rates). */
	readonly coingeckoId: string | null
	/** keccak256(pair), lowercase 0x-prefixed bytes32. Opaque to this workflow. */
	readonly feedId: string
}

export const ROSTER_CHAIN_ID = ${shared.chainId}

export const ROSTER: readonly RosterCoin[] = [
${body}
]
`

await Bun.write(target, out)
console.log(`wrote cre/market-meta/roster.ts (${rows.length} coins)`)
