import { writeFileSync } from 'node:fs';
import { createWalletClient, http, formatEther } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import { abis, chain, deployment, publicClient, feeParams, RPC_URL } from './chain.js';
import { usdcPermit } from './test-util.mjs';
const api = process.env.RELAY || 'https://relay-production-9f6c.up.railway.app';
const health = await (await fetch(`${api}/api/health`)).json();
if (!health.ok || !health.persistent || health.chain.chainId !== 5042002 || chain.id !== 5042002) throw Error('Not persistent testnet');
const account = privateKeyToAccount(process.env.DEPLOYER_PRIVATE_KEY);
const pub = publicClient();
const fee = await pub.readContract({address:deployment.cards,abi:abis.cards,functionName:'mintFee'});
const call={address:deployment.cards,abi:abis.cards,functionName:'mint',args:[0,await usdcPermit(account,pub,chain.id,deployment.cards,fee)]};
const gas=(await pub.estimateContractGas({account,...call}))*115n/100n;
const fees=await feeParams();
const ceiling=gas*fees.maxFeePerGas+fee*10n**12n;
if(ceiling>200000000000000000n)throw Error('Exceeds 0.2 USDC');
const hash=await createWalletClient({account,chain,transport:http(RPC_URL)}).writeContract({...call,gas,...fees});
const receipt=await pub.waitForTransactionReceipt({hash});
if(receipt.status!=='success')throw Error('Mint failed');
const result={network:'Live Arc testnet',api,action:'Mint BTC fighter',hash,feeUSDC:Number(fee)/1e6,maxCostUSDC:formatEther(ceiling),gasUsed:receipt.gasUsed.toString()};
writeFileSync(new URL('../docs/screens/hosted/action.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
