#!/usr/bin/env node
// Sync the indexer with the rest of the repo:
//   1. copy the three contract ABIs from shared/abi into indexer/abis
//   2. regenerate src/roster.generated.ts from shared/roster.json
//   3. if shared/deployments/<chainId>.json exists, rewrite config.yaml's
//      contract addresses and start_block from it
//
//   node scripts/sync-addresses.mjs              # chain 10143 (Monad testnet)
//   node scripts/sync-addresses.mjs --chain 31337 --config config.local.yaml   # local anvil
//   node scripts/sync-addresses.mjs --check      # exit 1 if config.yaml still has placeholders
//
// Idempotent: run it after every deploy, then `pnpm codegen`.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const indexerDir = join(here, "..");
const repoDir = join(indexerDir, "..");
const sharedDir = join(repoDir, "shared");

const args = process.argv.slice(2);
const chainArg = args.indexOf("--chain");
const chainId = chainArg >= 0 ? Number(args[chainArg + 1]) : 10143;
const checkOnly = args.includes("--check");

const CONTRACTS = [
  // config.yaml contract name -> key in shared/deployments/<chainId>.json
  { name: "MempireCards", key: "cards" },
  { name: "MempireArena", key: "arena" },
  { name: "MarketMeta", key: "marketMeta" },
];

const configArg = args.indexOf("--config");
const configPath = join(indexerDir, configArg >= 0 ? args[configArg + 1] : "config.yaml");

if (checkOnly) {
  const cfg = readFileSync(configPath, "utf8");
  if (cfg.includes("# TODO: set from shared/deployments")) {
    console.error("config.yaml still has placeholder addresses — run `node scripts/sync-addresses.mjs` after deploying.");
    process.exit(1);
  }
  console.log("config.yaml addresses are set.");
  process.exit(0);
}

// 1. ABIs ─────────────────────────────────────────────────────────────────────
for (const { name } of CONTRACTS) {
  const src = join(sharedDir, "abi", `${name}.json`);
  if (!existsSync(src)) {
    console.error(`missing ${src}`);
    process.exit(1);
  }
  copyFileSync(src, join(indexerDir, "abis", `${name}.json`));
}
console.log(`abis: copied ${CONTRACTS.map((c) => c.name).join(", ")}`);

// 2. Roster ───────────────────────────────────────────────────────────────────
const roster = JSON.parse(readFileSync(join(sharedDir, "roster.json"), "utf8"));
const rows = roster.coins.map((c) => ({
  coinId: c.coinId,
  ticker: c.ticker,
  name: c.name,
  kind: c.kind,
  feedId: String(c.feedId).toLowerCase(),
}));
const rosterTs = `// Generated by scripts/sync-addresses.mjs from shared/roster.json — do not edit.
// The chain only knows a coin's feed id and ticker; the roster adds its name and
// kind (crypto / meme / stock). Matched by Pyth feed id, then by coinId.

export type RosterKind = "crypto" | "meme" | "stock";

export interface RosterCoin {
  coinId: number;
  ticker: string;
  name: string;
  kind: RosterKind;
  feedId: string;
}

export const ROSTER: readonly RosterCoin[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(indexerDir, "src", "roster.generated.ts"), rosterTs);
console.log(`roster: ${rows.length} coins -> src/roster.generated.ts`);

// 3. Addresses ────────────────────────────────────────────────────────────────
const deploymentPath = join(sharedDir, "deployments", `${chainId}.json`);
if (!existsSync(deploymentPath)) {
  console.log(`addresses: ${deploymentPath} not found yet — config.yaml left as is.`);
  process.exit(0);
}
const dep = JSON.parse(readFileSync(deploymentPath, "utf8"));
if (Number(dep.chainId) !== chainId) {
  console.error(`deployment file says chainId ${dep.chainId}, expected ${chainId}`);
  process.exit(1);
}

let cfg = readFileSync(configPath, "utf8");
const chainBlock = new RegExp(`(- id: ${chainId}\\b[^\\n]*\\n)([\\s\\S]*?)(?=\\n  - id: |$)`);
const m = cfg.match(chainBlock);
if (!m) {
  console.error(`${configPath} has no chain with id ${chainId}`);
  process.exit(1);
}
let block = m[2];

const startBlock = Number(dep.startBlock ?? 0);
block = block.replace(
  /start_block: *\d+[^\n]*/,
  `start_block: ${startBlock} # from shared/deployments/${chainId}.json (startBlock)`,
);

for (const { name, key } of CONTRACTS) {
  const addr = dep[key];
  if (!/^0x[0-9a-fA-F]{40}$/.test(addr ?? "")) {
    console.error(`deployment file has no valid "${key}" address`);
    process.exit(1);
  }
  const re = new RegExp(`(- name: ${name}\\n(\\s+)address: )"0x[0-9a-fA-F]{40}"[^\\n]*`);
  if (!re.test(block)) {
    console.error(`config.yaml chain ${chainId} has no address line for ${name}`);
    process.exit(1);
  }
  block = block.replace(re, `$1"${addr}" # from shared/deployments/${chainId}.json (${key})`);
}

cfg = cfg.replace(chainBlock, `${m[1]}${block}`);
writeFileSync(configPath, cfg);
console.log(
  `addresses: chain ${chainId} start_block ${startBlock}; ` +
    CONTRACTS.map(({ name, key }) => `${name}=${dep[key]}`).join(", "),
);
console.log("next: pnpm codegen");
