#!/usr/bin/env node
// Sync the indexer with the rest of the repo:
//   1. copy the four indexed contract ABIs from shared/abi into indexer/abis
//   2. regenerate src/roster.generated.ts from shared/roster.json
//   3. if shared/deployments/<chainId>.json exists, rewrite that chain's config
//      file (contract addresses and start_block) from it. MempireCCIPGateway
//      is optional: a missing or zero `ccipGateway` (no CCIP_ROUTER at deploy)
//      keeps its placeholder address, which emits nothing.
//
//   node scripts/sync-addresses.mjs                  # Arc testnet 5042002 -> config.yaml
//   node scripts/sync-addresses.mjs --chain 5042     # Arc mainnet         -> config.mainnet.yaml
//   node scripts/sync-addresses.mjs --chain 31337    # arc-anvil fork      -> config.local.yaml
//   node scripts/sync-addresses.mjs --check [--chain N]   # exit 1 while that config has placeholders
//   ... --config <file>                              # override the config file
//
// Idempotent: run it after every deploy, then `pnpm codegen`.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const indexerDir = join(here, "..");
const repoDir = join(indexerDir, "..");
const sharedDir = join(repoDir, "shared");

const args = process.argv.slice(2);
const chainArg = args.indexOf("--chain");
const chainId = chainArg >= 0 ? Number(args[chainArg + 1]) : 5042002;
/** Which config file indexes which chain. */
const CONFIG_FOR_CHAIN = { 5042002: "config.yaml", 5042: "config.mainnet.yaml", 31337: "config.local.yaml" };
const checkOnly = args.includes("--check");

const CONTRACTS = [
  // config.yaml contract name -> key in shared/deployments/<chainId>.json
  { name: "MempireCards", key: "cards" },
  { name: "MempireArena", key: "arena" },
  { name: "MarketMeta", key: "marketMeta" },
  // Only deployed when the chain has a CCIP router (Deploy.s.sol CCIP_ROUTER).
  { name: "MempireCCIPGateway", key: "ccipGateway", optional: true },
];
const ZERO_ADDRESS = "0x0000000000000000000000000000000000000000";
const PLACEHOLDER = { MempireCCIPGateway: "0x00000000000000000000000000000000000c0de4" };

const configArg = args.indexOf("--config");
const configName = configArg >= 0 ? args[configArg + 1] : CONFIG_FOR_CHAIN[chainId];
if (!configName) {
  console.error(`no config file for chain ${chainId} — pass --config <file>`);
  process.exit(1);
}
const configPath = join(indexerDir, configName);

if (checkOnly) {
  const cfg = readFileSync(configPath, "utf8");
  if (cfg.includes("# TODO: set from shared/deployments")) {
    console.error(`${configName} still has placeholder addresses — run \`node scripts/sync-addresses.mjs --chain ${chainId}\` after deploying.`);
    process.exit(1);
  }
  console.log(`${configName} addresses are set.`);
  process.exit(0);
}

// 1. ABIs ─────────────────────────────────────────────────────────────────────
for (const { name } of CONTRACTS) {
  const src = join(sharedDir, "abi", `${name}.json`);
  if (!existsSync(src)) {
    console.error(`missing ${src}`);
    process.exit(1);
  }
  copyFileSync(src, join(indexerDir, "abis", `${name}.json`));
}
console.log(`abis: copied ${CONTRACTS.map((c) => c.name).join(", ")}`);

// 2. Roster ───────────────────────────────────────────────────────────────────
const roster = JSON.parse(readFileSync(join(sharedDir, "roster.json"), "utf8"));
const rows = roster.coins.map((c) => ({
  coinId: c.coinId,
  ticker: c.ticker,
  name: c.name,
  kind: c.kind,
  pair: c.pair,
  feedId: String(c.feedId).toLowerCase(),
  feed: String(c.feed).toLowerCase(),
  decimals: Number(c.decimals),
}));
const KINDS = ["crypto", "defi", "rwa"];
for (const r of rows) {
  if (!KINDS.includes(r.kind)) {
    console.error(`roster coin ${r.coinId} (${r.ticker}) has kind "${r.kind}"; expected one of ${KINDS.join(", ")}`);
    process.exit(1);
  }
}
const rosterTs = `// Generated by scripts/sync-addresses.mjs from shared/roster.json — do not edit.
// The chain only knows a coin's feed id (keccak256 of the Chainlink pair) and
// ticker; the roster adds its name, kind (crypto / defi / rwa) and Chainlink
// Data Feed on Arc mainnet. Matched by feed id, then by coinId.

export type RosterKind = "crypto" | "defi" | "rwa";

export interface RosterCoin {
  coinId: number;
  ticker: string;
  name: string;
  kind: RosterKind;
  /** The Chainlink pair, e.g. "BTC / USD". */
  pair: string;
  /** keccak256(pair), lowercase: the coin's identity on every chain. */
  feedId: string;
  /** Chainlink AggregatorV3 proxy on Arc mainnet, lowercase. Testnet may use a mirror instead. */
  feed: string;
  /** The feed's answer decimals (a minted card's mintExpo is −decimals). */
  decimals: number;
}

export const ROSTER: readonly RosterCoin[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(join(indexerDir, "src", "roster.generated.ts"), rosterTs);
console.log(`roster: ${rows.length} coins -> src/roster.generated.ts`);

// 3. Addresses ────────────────────────────────────────────────────────────────
const deploymentPath = join(sharedDir, "deployments", `${chainId}.json`);
if (!existsSync(deploymentPath)) {
  console.log(`addresses: ${deploymentPath} not found yet — ${configName} left as is.`);
  process.exit(0);
}
const dep = JSON.parse(readFileSync(deploymentPath, "utf8"));
if (Number(dep.chainId) !== chainId) {
  console.error(`deployment file says chainId ${dep.chainId}, expected ${chainId}`);
  process.exit(1);
}

let cfg = readFileSync(configPath, "utf8");
const chainBlock = new RegExp(`(- id: ${chainId}\\b[^\\n]*\\n)([\\s\\S]*?)(?=\\n  - id: |$)`);
const m = cfg.match(chainBlock);
if (!m) {
  console.error(`${configPath} has no chain with id ${chainId}`);
  process.exit(1);
}
let block = m[2];

const startBlock = Number(dep.startBlock ?? 0);
block = block.replace(
  /start_block: *\d+[^\n]*/,
  `start_block: ${startBlock} # from shared/deployments/${chainId}.json (startBlock)`,
);

const synced = [];
for (const { name, key, optional } of CONTRACTS) {
  const addr = dep[key];
  const re = new RegExp(`(- name: ${name}\\n(\\s+)address: )"0x[0-9a-fA-F]{40}"[^\\n]*`);
  if (!re.test(block)) {
    console.error(`${configName} chain ${chainId} has no address line for ${name}`);
    process.exit(1);
  }
  if (optional && (addr === undefined || String(addr).toLowerCase() === ZERO_ADDRESS)) {
    // Not deployed on this chain: keep a placeholder (no code, no events).
    block = block.replace(re, `$1"${PLACEHOLDER[name]}" # not deployed: shared/deployments/${chainId}.json has no ${key}`);
    synced.push(`${name}=(not deployed)`);
    continue;
  }
  if (!/^0x[0-9a-fA-F]{40}$/.test(addr ?? "")) {
    console.error(`deployment file has no valid "${key}" address`);
    process.exit(1);
  }
  block = block.replace(re, `$1"${addr}" # from shared/deployments/${chainId}.json (${key})`);
  synced.push(`${name}=${addr}`);
}

cfg = cfg.replace(chainBlock, `${m[1]}${block}`);
writeFileSync(configPath, cfg);
console.log(`addresses: chain ${chainId} start_block ${startBlock}; ${synced.join(", ")}`);
console.log(`next: pnpm exec envio codegen --config ${configName}`);
